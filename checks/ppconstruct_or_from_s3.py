"""Check that S3^[3] pp-constructs the Lichter-Pago template OR_T[Z2^[3], Z3^[3]].

We build the 3rd pp-power Delta of S3 described in the note and verify, exhaustively:
  1. every relation of Delta is a coset of a subgroup of the appropriate power of S3
     (closed under x y^-1 z), so it is a relation of S3^[9] / S3^[6];
  2. h1 : A7 -> Delta and h2 : Delta -> A7 are homomorphisms.
Relations of Delta and the map h2 only look at the "features" of an element
z = (g1, g2, g3) in S3^3, namely (sign g1, rot g1, sign g2, sign g3). Membership is
defined through features, so checking all feature triples is exhaustive; we also check
on random full elements that this is consistent.

Run: python3 -I ppconstruct_or_from_s3.py
"""

import itertools
import random

# S3 = Z3 x| Z2, element (a, s), (a,s)(b,t) = (a + (-1)^s b, s+t)
S3 = [(a, s) for s in range(2) for a in range(3)]


def mul(x, y):
    a, s = x
    b, t = y
    return ((a + (b if s == 0 else -b)) % 3, (s + t) % 2)


def inv(x):
    a, s = x
    # (a,s)^-1 = (-(−1)^s a, s): check (a,s)(c,s) = (a + (-1)^s c, 0) = 0
    c = (-a) % 3 if s == 0 else a % 3
    return (c, s)


for x in S3:
    assert mul(x, inv(x)) == (0, 0) and mul(inv(x), x) == (0, 0)


def maltsev(x, y, z):
    return mul(mul(x, inv(y)), z)


def is_coset(rel):
    """rel: set of tuples over S3. Coset of a subgroup iff nonempty and closed under x y^-1 z."""
    rel = set(rel)
    if not rel:
        return False
    for x in rel:
        for y in rel:
            for z in rel:
                w = tuple(maltsev(a, b, c) for a, b, c in zip(x, y, z))
                if w not in rel:
                    return False
    return True


# ---------- cosets of subgroups of Z_p^3 ----------
def subgroups_Zp3(p):
    vecs = list(itertools.product(range(p), repeat=3))
    subs = set()
    # every subgroup of Z_p^3 is generated by at most 3 vectors
    for gens in itertools.combinations_with_replacement(vecs, 3):
        span = set()
        for coeffs in itertools.product(range(p), repeat=3):
            v = tuple(sum(c * g[i] for c, g in zip(coeffs, gens)) % p for i in range(3))
            span.add(v)
        subs.add(frozenset(span))
    return subs


def cosets_Zp3(p):
    out = set()
    for H in subgroups_Zp3(p):
        for w in itertools.product(range(p), repeat=3):
            out.add(frozenset(tuple((h[i] + w[i]) % p for i in range(3)) for h in H))
    return out


Z2_COSETS = sorted(cosets_Zp3(2), key=lambda c: sorted(c))
Z3_COSETS = sorted(cosets_Zp3(3), key=lambda c: sorted(c))
print(f"cosets of subgroups: Z2^3 -> {len(Z2_COSETS)}, Z3^3 -> {len(Z3_COSETS)}")


def subgroup_and_rep(coset, p):
    w = min(coset)
    H = frozenset(tuple((x[i] - w[i]) % p for i in range(3)) for x in coset)
    return H, w


# ---------- the template A7 = OR_T[Z2^[3], Z3^[3]] ----------
A7 = [("z2", 0), ("z2", 1), ("z3", 0), ("z3", 1), ("z3", 2), ("c1",), ("c2",)]


def rel_A7_z2(coset):
    rel = {tuple(("z2", t) for t in tup) for tup in coset}
    rel.add((("c1",),) * 3)
    return rel


def rel_A7_z3(coset):
    rel = {tuple(("z3", b) for b in tup) for tup in coset}
    rel.add((("c2",),) * 3)
    return rel


S_A7 = {(("z2", t), ("c2",)) for t in range(2)} | {(("c1",), ("z3", b)) for b in range(3)}


# ---------- the pp-power Delta (universe S3^3) ----------
def feat(z):
    g1, g2, g3 = z
    return (g1[1], g1[0], g2[1], g3[1])  # sign g1, rot g1, sign g2 (selector), sign g3 (marker)


def in_delta_z2(zs, coset):
    H, w = subgroup_and_rep(coset, 2)
    fs = [feat(z) for z in zs]
    if any(f[3] != 0 for f in fs):
        return False
    sel = {f[2] for f in fs}
    if len(sel) != 1:
        return False
    sigma = sel.pop()
    t = tuple(f[0] for f in fs)
    # condition: t + sigma*w in coset  (sigma=0: t in R; sigma=1: t in R0)
    return tuple((t[i] + sigma * w[i]) % 2 for i in range(3)) in coset


def in_delta_z3(zs, coset):
    H, w = subgroup_and_rep(coset, 3)
    fs = [feat(z) for z in zs]
    if any(f[3] != 1 for f in fs):
        return False
    signs = {f[0] for f in fs}
    if len(signs) != 1:
        return False
    s = signs.pop()
    a = tuple(f[1] for f in fs)
    # condition: a in H + s*w
    return tuple((a[i] - s * w[i]) % 3 for i in range(3)) in H


def in_delta_S(z, zp):
    f, fp = feat(z), feat(zp)
    return f[3] == 0 and fp[3] == 1 and f[2] == fp[0]


def h2(z):
    f = feat(z)
    if f[3] == 0:
        return ("z2", f[0]) if f[2] == 0 else ("c1",)
    return ("z3", f[1]) if f[0] == 1 else ("c2",)


def h1(x):
    e = (0, 0)
    if x[0] == "z2":
        return ((0, x[1]), e, e)
    if x[0] == "c1":
        return (e, (0, 1), e)
    if x[0] == "z3":
        return ((x[1], 1), e, (0, 1))
    return (e, e, (0, 1))  # c2


# representatives of the 24 feature classes
REPS = {}
for z in itertools.product(S3, repeat=3):
    REPS.setdefault(feat(z), z)
assert len(REPS) == 24
reps = list(REPS.values())

# 1. h2 is a homomorphism Delta -> A7 (exhaustive over feature triples)
for coset in Z2_COSETS:
    relA = rel_A7_z2(coset)
    for zs in itertools.product(reps, repeat=3):
        if in_delta_z2(zs, coset):
            assert tuple(h2(z) for z in zs) in relA, (coset, zs)
for coset in Z3_COSETS:
    relA = rel_A7_z3(coset)
    for zs in itertools.product(reps, repeat=3):
        if in_delta_z3(zs, coset):
            assert tuple(h2(z) for z in zs) in relA, (coset, zs)
for z, zp in itertools.product(reps, repeat=2):
    if in_delta_S(z, zp):
        assert (h2(z), h2(zp)) in S_A7
print("h2 : Delta -> A7 is a homomorphism")

# 2. h1 is a homomorphism A7 -> Delta
for coset in Z2_COSETS:
    for tup in rel_A7_z2(coset):
        assert in_delta_z2([h1(x) for x in tup], coset)
for coset in Z3_COSETS:
    for tup in rel_A7_z3(coset):
        assert in_delta_z3([h1(x) for x in tup], coset)
for x, y in S_A7:
    assert in_delta_S(h1(x), h1(y))
print("h1 : A7 -> Delta is a homomorphism")

# 3. each relation of Delta is a coset in a power of S3.
# Coordinates not mentioned by the defining condition are free, and a product of a coset
# with a full power is a coset, so it suffices to check the coordinates that occur:
#   Z2 relations: (g1, g2) of each of the 3 elements plus g3 (marker)  -> sign data only;
#   Z3 relations: g1 and g3 of each element;  S: g2, g3 of the first and g1, g3 of the second.
# The full 9-coordinate check is 6^9 ~ 10^7 tuples per relation, too slow in pure Python
# for all 51 Z2 cosets. Membership in the Z2 relations depends only on signs, and the sign
# map S3 -> Z2 is a homomorphism, so the relation is the preimage of a set of sign vectors;
# the preimage of a subset of Z2^9 under a surjective homomorphism is a coset iff the subset
# is an affine subspace. We check that instead.
def sign_vectors_z2(coset):
    out = set()
    for bits in itertools.product(range(2), repeat=9):
        # bits = (sg g1, sg g2, sg g3) for each of the three elements
        zs = []
        for j in range(3):
            g1 = (0, bits[3 * j]); g2 = (0, bits[3 * j + 1]); g3 = (0, bits[3 * j + 2])
            zs.append((g1, g2, g3))
        if in_delta_z2(zs, coset):
            out.add(bits)
    return out


def is_affine_Z2(vecs):
    vecs = list(vecs)
    if not vecs:
        return False
    v0 = vecs[0]
    diffs = {tuple((a - b) % 2 for a, b in zip(v, v0)) for v in vecs}
    for d1 in diffs:
        for d2 in diffs:
            if tuple((a + b) % 2 for a, b in zip(d1, d2)) not in diffs:
                return False
    return True


for coset in Z2_COSETS:
    assert is_affine_Z2(sign_vectors_z2(coset)), coset
print("Delta's Z2-relations are cosets (preimages of affine subspaces of Z2^9)")

# Z3 relations: the g2 coordinates are free; check the 6 coordinates g1, g3 of each element.
for coset in Z3_COSETS:
    rel = set()
    for g1s in itertools.product(S3, repeat=3):
        for marks in itertools.product(range(2), repeat=3):
            zs = [(g1s[j], (0, 0), (0, marks[j])) for j in range(3)]
            if in_delta_z3(zs, coset):
                # store (g1_1, g1_2, g1_3) together with marker signs; markers must all be 1
                rel.add(g1s + tuple((0, m) for m in marks))
    # markers are forced to sign 1; their rotation part is free, so the relation on the
    # 6 coordinates is (relation on g1s) x (sign-1 coset)^3; check the g1 part
    g1rel = {t[:3] for t in rel}
    assert is_coset(g1rel), coset
print("Delta's Z3-relations are cosets")

# S relation: depends only on signs (g2, g3 of z; g1, g3 of z'): preimage of a sign set.
svecs = set()
for bits in itertools.product(range(2), repeat=6):
    z = ((0, bits[0]), (0, bits[1]), (0, bits[2]))
    zp = ((0, bits[3]), (0, bits[4]), (0, bits[5]))
    if in_delta_S(z, zp):
        svecs.add(bits)
assert is_affine_Z2(svecs)
print("Delta's S relation is a coset (preimage of an affine subspace of Z2^6)")

# 3b. pp-definability from ternary cosets of S3.
# Each Z2-relation of Delta is: markers 0 (unary sign cosets), selectors equal (binary sign
# equalities, padded to arity 3), and an affine condition on the four sign bits
# (sg z1^1, sg z2^1, sg z3^1, selector). Write that condition in reduced echelon form; an
# equation on 1, 2 or 3 bits is one ternary coset of S3^3 (a preimage under sg, padded with
# repeated variables), and an equation on 4 bits is two ternary cosets sharing one
# existentially quantified auxiliary element. Because sg : S3 -> Z2 is onto, it suffices to
# evaluate the formula on sign bits, quantifying the auxiliary bit.
def affine_equations(vecs, n):
    """Equations (row, rhs) in reduced echelon form defining the affine subspace `vecs` of Z2^n."""
    vecs = list(vecs)
    v0 = vecs[0]
    diffs = [tuple((a - b) % 2 for a, b in zip(v, v0)) for v in vecs]
    eqs = []
    for row in itertools.product(range(2), repeat=n):
        if any(row) and all(sum(r * d for r, d in zip(row, dv)) % 2 == 0 for dv in diffs):
            eqs.append(row)
    # reduce to a basis in echelon form
    basis = []
    for row in eqs:
        r = list(row)
        for b, pc in basis:
            if r[pc]:
                r = [(x + y) % 2 for x, y in zip(r, b)]
        if any(r):
            pc = r.index(1)
            basis = [([(x + y) % 2 for x, y in zip(b, r)] if b[pc] else b, bpc) for b, bpc in basis]
            basis.append((r, pc))
    return [(tuple(b), sum(x * y for x, y in zip(b, v0)) % 2) for b, _ in basis]


def eval_pp_formula(eqs, bits):
    """Evaluate the conjunction of ternary atoms (with one auxiliary bit per 4-term equation)."""
    for row, rhs in eqs:
        idx = [i for i in range(len(row)) if row[i]]
        if len(idx) <= 3:
            if sum(bits[i] for i in idx) % 2 != rhs:
                return False
        else:
            a, b, c, d = idx
            # exists y: T_0(x_a, x_b, y) and T_rhs(y, x_c, x_d)
            if not any((bits[a] + bits[b] + y) % 2 == 0 and (y + bits[c] + bits[d]) % 2 == rhs
                       for y in range(2)):
                return False
    return True


max_aux = 0
for coset in Z2_COSETS:
    H, w = subgroup_and_rep(coset, 2)
    A = {t + (s,) for t in itertools.product(range(2), repeat=3) for s in range(2)
         if tuple((t[i] + s * w[i]) % 2 for i in range(3)) in coset}
    eqs = affine_equations(A, 4)
    max_aux = max(max_aux, sum(1 for row, _ in eqs if sum(row) == 4))
    for bits in itertools.product(range(2), repeat=9):
        # bits = (sg g1, sg g2, sg g3) of each element
        markers_ok = all(bits[3 * j + 2] == 0 for j in range(3))
        sel_ok = bits[1] == bits[4] == bits[7]
        formula = markers_ok and sel_ok and eval_pp_formula(eqs, (bits[0], bits[3], bits[6], bits[1]))
        zs = [((0, bits[3 * j]), (0, bits[3 * j + 1]), (0, bits[3 * j + 2])) for j in range(3)]
        assert formula == in_delta_z2(zs, coset), (coset, bits)
print(f"Delta's Z2-relations are pp-definable from ternary cosets of S3 "
      f"(at most {max_aux} auxiliary variable per relation)")

# 4. random full-element consistency check of feature-based definitions
random.seed(1)
for _ in range(20000):
    zs = [tuple(random.choice(S3) for _ in range(3)) for _ in range(3)]
    for coset in random.sample(Z2_COSETS, 3):
        assert in_delta_z2(zs, coset) == in_delta_z2([REPS[feat(z)] for z in zs], coset)
print("all checks passed")
